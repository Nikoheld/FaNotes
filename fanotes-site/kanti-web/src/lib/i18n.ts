export const STRINGS = { de, en }
export type Language = keyof typeof STRINGS

export const pickLanguage = (choice: string, browserLanguages: readonly string[] = []): Language => {
  if (choice === 'de' || choice === 'en') return choice
  const first = browserLanguages.find((language) => /^(de|en)\b/iu.test(language)) || 'de'
  return first.toLowerCase().startsWith('en') ? 'en' : 'de'
}

export const dateLabel = (iso: string, language: Language, options: Intl.DateTimeFormatOptions = { weekday: 'short', day: 'numeric', month: 'short' }) => {
  if (!/^\d{4}-\d{2}-\d{2}/u.test(iso)) return iso
  const [year, month, day] = iso.slice(0, 10).split('-').map(Number)
  return new Intl.DateTimeFormat(language === 'de' ? 'de-CH' : 'en-GB', { ...options, timeZone: 'UTC' }).format(new Date(Date.UTC(year, month - 1, day)))
}

/** "3", "2,5" (German) or "2.5". */
export const pointsLabel = (value: number, language: Language) => {
  const rounded = Math.round(value * 10) / 10
  const text = Number.isInteger(rounded) ? String(rounded) : rounded.toFixed(1)
  return language === 'de' ? text.replace('.', ',') : text
}

export const markLabel = (mark: number | null | undefined, digits = 2) => {
  if (mark == null || !Number.isFinite(mark)) return '–'
  return Number(mark.toFixed(digits)).toString()
}
