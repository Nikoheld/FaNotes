// Rebuilds electron/onenote-sanitizer.bundle.cjs from scripts/onenote-sanitizer-entry.mjs.
//
//   node scripts/build-onenote-sanitizer.mjs           # write the bundle
//   node scripts/build-onenote-sanitizer.mjs --check   # fail when the committed bundle is stale
//
// The Electron main process ships without node_modules (check-startup-preflight
// requires an empty `dependencies`), so parse5 and hast-util-sanitize are bundled
// from the pinned devDependencies with esbuild.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const appRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const target = join(appRoot, 'electron', 'onenote-sanitizer.bundle.cjs')

export async function bundleOneNoteSanitizer() {
  const result = await build({
    absWorkingDir: appRoot,
    entryPoints: ['scripts/onenote-sanitizer-entry.mjs'],
    bundle: true,
    format: 'cjs',
    platform: 'node',
    target: 'node20',
    write: false,
    minify: true,
    legalComments: 'eof',
    charset: 'utf8',
    banner: { js: '// Generated by scripts/build-onenote-sanitizer.mjs from scripts/onenote-sanitizer-entry.mjs. Do not edit.' },
  })
  return result.outputFiles[0].text
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await bundleOneNoteSanitizer()
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== text) {
      console.error('electron/onenote-sanitizer.bundle.cjs is stale: run node scripts/build-onenote-sanitizer.mjs')
      process.exit(1)
    }
    console.log('onenote-sanitizer bundle is up to date')
  } else {
    writeFileSync(target, text)
    console.log(`wrote ${target} (${text.length} bytes)`)
  }
}
