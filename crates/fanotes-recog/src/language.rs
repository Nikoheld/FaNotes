//! Common-word lists, bigrams and trigrams copied from `src/data/*Language.ts`.
//! Order matches the JavaScript `Set` insertion order the CTC word search walks.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Language {
    De,
    En,
}

impl Language {
    pub fn parse(value: &str) -> Option<Self> {
        match value {
            "de" => Some(Self::De),
            "en" => Some(Self::En),
            _ => None,
        }
    }
}

pub(crate) struct Lexicon {
    pub(crate) words: &'static [&'static str],
    pub(crate) bigrams: &'static [&'static str],
    pub(crate) trigrams: &'static [&'static str],
}

pub(crate) fn lexicon(language: Language) -> Lexicon {
    match language {
        Language::De => Lexicon {
            words: DE_WORDS,
            bigrams: DE_BIGRAMS,
            trigrams: DE_TRIGRAMS,
        },
        Language::En => Lexicon {
            words: EN_WORDS,
            bigrams: EN_BIGRAMS,
            trigrams: EN_TRIGRAMS,
        },
    }
}

