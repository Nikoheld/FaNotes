use fanotes_host::Host;
use serde_json::json;

fn scratch(name: &str) -> (std::path::PathBuf, Host) {
    let dir = std::env::temp_dir().join(format!("fanotes-addons-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(dir.join("vault")).unwrap();
    let mut host = Host::open(dir.join("app"));
    host.set_vault(dir.join("vault")).unwrap();
    (dir, host)
}

#[test]
fn installed_addons_stay_outside_the_vault() {
    let (_dir, mut host) = scratch("store");
    host.dispatch(
        "fanotes:addons-save",
        &[json!({
            "id": "margin-notes",
            "enabled": true,
            "manifest": { "name": "Margin Notes" }
        })],
    )
    .unwrap();
    host.dispatch(
        "fanotes:addons-write-files",
        &[
            json!("margin-notes"),
            json!({ "main.js": "export {}", "../secret": "no" }),
        ],
    )
    .unwrap_err();
    host.dispatch(
        "fanotes:addons-write-files",
        &[json!("margin-notes"), json!({ "main.js": "export {}" })],
    )
    .unwrap();
    host.dispatch(
        "fanotes:addons-write-data",
        &[json!("margin-notes"), json!("{\"open\":1}")],
    )
    .unwrap();

    let listed = host.dispatch("fanotes:addons-list", &[]).unwrap();
    assert_eq!(listed[0]["id"], "margin-notes");
    assert_eq!(
        host.dispatch(
            "fanotes:addons-read-file",
            &[json!("margin-notes"), json!("main.js")]
        )
        .unwrap(),
        "export {}"
    );
    assert_eq!(
        host.dispatch("fanotes:addons-read-data", &[json!("margin-notes")])
            .unwrap(),
        "{\"open\":1}"
    );
    assert!(host
        .dispatch(
            "fanotes:addons-read-file",
            &[json!("margin-notes"), json!("missing.js")]
        )
        .unwrap()
        .is_null());

    host.dispatch("fanotes:addons-remove", &[json!("margin-notes")])
        .unwrap();
    assert_eq!(
        host.dispatch("fanotes:addons-list", &[])
            .unwrap()
            .as_array()
            .unwrap()
            .len(),
        0
    );
    assert!(host
        .dispatch("fanotes:addons-save", &[json!({ "id": "../vault" })])
        .is_err());
    assert!(host
        .dispatch(
            "fanotes:addons-fetch",
            &[json!("https://example.com/addon.js")]
        )
        .is_err());
    assert!(host
        .dispatch(
            "fanotes:addons-net-fetch",
            &[json!("https://127.0.0.1/hook"), json!({})]
        )
        .is_err());
}

#[test]
fn registry_and_network_reads_use_public_https() {
    let (_dir, mut host) = scratch("network");
    let text = host
        .dispatch(
            "fanotes:addons-fetch",
            &[json!(
                "https://raw.githubusercontent.com/github/gitignore/main/Rust.gitignore"
            )],
        )
        .unwrap();
    assert!(text.as_str().unwrap_or("").contains("Generated by Cargo"));
    let response = host
        .dispatch(
            "fanotes:addons-net-fetch",
            &[json!("https://example.com/"), json!({ "method": "GET" })],
        )
        .unwrap();
    assert_eq!(response["status"], 200);
    assert!(response["body"]
        .as_str()
        .unwrap_or("")
        .contains("Example Domain"));
}

#[test]
fn a_symlinked_addon_store_is_not_followed() {
    let (dir, mut host) = scratch("symlink");
    let outside = dir.join("outside");
    std::fs::create_dir_all(&outside).unwrap();
    std::fs::write(outside.join("secret"), b"geheim").unwrap();
    #[cfg(unix)]
    std::os::unix::fs::symlink(&outside, dir.join("app/addons")).unwrap();
    let listed = host.dispatch("fanotes:addons-list", &[]);
    #[cfg(unix)]
    {
        assert!(listed.unwrap_err().contains("unsicher"));
        assert_eq!(std::fs::read(outside.join("secret")).unwrap(), b"geheim");
        assert!(!outside.join("addons.json").exists());
    }
    #[cfg(not(unix))]
    {
        assert!(listed.is_ok());
    }

    let (_dir, mut host) = scratch("data-link");
    host.dispatch(
        "fanotes:addons-write-data",
        &[json!("margin-notes"), json!("{\"open\":1}")],
    )
    .unwrap();
    let data = _dir.join("app/addons/margin-notes.data.json");
    std::fs::remove_file(&data).unwrap();
    std::fs::write(outside.join("data"), b"leak").unwrap();
    #[cfg(unix)]
    {
        std::os::unix::fs::symlink(outside.join("data"), &data).unwrap();
        assert!(host
            .dispatch("fanotes:addons-read-data", &[json!("margin-notes")])
            .unwrap_err()
            .contains("unsicher"));
        assert!(host
            .dispatch(
                "fanotes:addons-write-data",
                &[json!("margin-notes"), json!("replaced")]
            )
            .unwrap_err()
            .contains("unsicher"));
        assert_eq!(std::fs::read(outside.join("data")).unwrap(), b"leak");
    }
}
