"""Kanti+ mark (the K+ of the earlier icon, redrawn): one geometry, emitted as SVG masters and Android
VectorDrawables, so every size is derived from the same vectors.

Usage: python3 gen.py <repo root>
"""
import math
import pathlib
import sys

REPO = pathlib.Path(sys.argv[1])
RES = REPO / "android/companion/src/main/res/drawable"
BRAND = REPO / "android/companion/docs/brand"

INK = "#143552"
PAPER = "#F6F8F6"
GOLD = "#E7B552"
SCALE = 0.92  # keeps every mark inside the 66 dp safe zone of the 108 dp canvas

# Primitives: ("rrect", x, y, w, h, r, color[, alpha]) ("circle", cx, cy, r, color) ("stroke", d, width, color)
# The K+ of the earlier mark (straight stem, arms meeting at the stem, a separate gold plus), drawn
# with one stroke weight, round terminals and the plus nested in the K's opening.
KANTI = [
    ("stroke", "M32.5,34 V74", 9.5, PAPER),
    ("stroke", "M55.5,34 L34.5,55 L55.5,74", 9.5, PAPER),
    ("stroke", "M60.5,54 H75.5 M68,46.5 V61.5", 9.5, GOLD),
]
SCHULE = [
    ("stroke", "M30,47 L54,31 L78,47", 7, PAPER),
    ("stroke", "M38,53 V69 M54,53 V69 M70,53 V69", 7, PAPER),
    ("stroke", "M31,76 H77", 7, PAPER),
    ("circle", 54, 40.5, 3.8, GOLD),
]
# Pages with the ruled lines cut out (even-odd), so the lines survive in the one-colour themed icon.
NOTIZ = [
    ("holed", (29, 32, 22, 44, 6), [(35, 42.4, 10, 3.2, 1.6), (35, 50.4, 10, 3.2, 1.6), (35, 58.4, 7, 3.2, 1.6)], PAPER),
    ("holed", (57, 32, 22, 44, 6), [(63, 42.4, 10, 3.2, 1.6), (63, 50.4, 7, 3.2, 1.6)], PAPER),
    ("stroke", "M62,66.5 H74 M68,60.5 V72.5", 4.5, GOLD),
]
MARKS = {"": KANTI, "_schule": SCHULE, "_notiz": NOTIZ}


def fmt(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def rrect_path(x, y, w, h, r):
    x, y, w, h, r = (fmt(v) for v in (x, y, w, h, r))
    x, y, w, h, r = (float(v) for v in (x, y, w, h, r))
    f = fmt
    return (f"M{f(x + r)},{f(y)}H{f(x + w - r)}A{f(r)},{f(r)} 0 0 1 {f(x + w)},{f(y + r)}V{f(y + h - r)}A{f(r)},{f(r)} 0 0 1 {f(x + w - r)},{f(y + h)}"
            f"H{f(x + r)}A{f(r)},{f(r)} 0 0 1 {f(x)},{f(y + h - r)}V{f(y + r)}A{f(r)},{f(r)} 0 0 1 {f(x + r)},{f(y)}Z")


def circle_path(cx, cy, r):
    f = fmt
    return f"M{f(cx - r)},{f(cy)}A{f(r)},{f(r)} 0 1 1 {f(cx + r)},{f(cy)}A{f(r)},{f(r)} 0 1 1 {f(cx - r)},{f(cy)}Z"


def as_paths(shapes, mono=False):
    """(pathData, fill, stroke, strokeWidth) tuples."""
    out = []
    for s in shapes:
        if s[0] == "holed":
            d = rrect_path(*s[1]) + "".join(rrect_path(*hole) for hole in s[2])
            out.append((d, "#000000" if mono else s[3], None, None, True))
            continue
        color = "#000000" if mono else s[6 if s[0] == "rrect" else 4 if s[0] == "circle" else 3]
        if s[0] == "rrect":
            out.append((rrect_path(*s[1:6]), color, None, None))
        elif s[0] == "circle":
            out.append((circle_path(*s[1:4]), color, None, None))
        else:
            if mono and s[3] == INK:
                continue  # ink details are cut-outs on paper; in one colour they would vanish anyway
            out.append((s[1], None, color, s[2]))
    return out


def group_open_svg(scale):
    t = 54 * (1 - scale)
    return f'<g transform="translate({fmt(t)} {fmt(t)}) scale({scale})">'


def svg(shapes, background=True, mono=False, view="0 0 108 108", size=108, scale=SCALE):
    body = []
    if background:
        body.append(f'<rect width="108" height="108" fill="{INK}"/>')
    body.append(group_open_svg(scale))
    for d, fill, stroke, width, *even in as_paths(shapes, mono):
        if stroke:
            body.append(f'<path d="{d}" fill="none" stroke="{stroke}" stroke-width="{fmt(width)}" stroke-linecap="round" stroke-linejoin="round"/>')
        else:
            body.append(f'<path d="{d}" fill="{fill}"{' fill-rule="evenodd"' if even else ''}/>')
    body.append("</g>")
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}" width="{size}" height="{size}">{"".join(body)}</svg>\n'


HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by android/companion/docs/brand/gen.py from the Kanti+ mark. Edit the generator, not this file. -->\n'


def vector(shapes, mono=False, size=108, viewport=108, scale=SCALE, translate=0.0, white=False):
    t = 54 * (1 - scale) + translate
    lines = [HEADER + '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             f'    android:width="{size}dp"', f'    android:height="{size}dp"',
             f'    android:viewportWidth="{fmt(viewport)}"', f'    android:viewportHeight="{fmt(viewport)}">',
             f'    <group android:translateX="{fmt(t)}" android:translateY="{fmt(t)}" android:scaleX="{scale}" android:scaleY="{scale}">']
    for d, fill, stroke, width, *even in as_paths(shapes, mono):
        color = "#FFFFFF" if white else None
        if stroke:
            lines.append(f'        <path android:pathData="{d}" android:fillColor="#00000000" android:strokeColor="{color or stroke}" '
                         f'android:strokeWidth="{fmt(width)}" android:strokeLineCap="round" android:strokeLineJoin="round" />')
        else:
            rule = ' android:fillType="evenOdd"' if even else ""
            lines.append(f'        <path android:pathData="{d}" android:fillColor="{color or fill}"{rule} />')
    lines.append("    </group>")
    lines.append("</vector>\n")
    return "\n".join(lines)


BACKGROUND = (HEADER + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp"\n    android:height="108dp"\n'
              '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
              f'    <path android:pathData="M0,0h108v108h-108z" android:fillColor="{INK}" />\n</vector>\n')

if __name__ == "__main__":
    BRAND.mkdir(parents=True, exist_ok=True)
    for suffix, shapes in MARKS.items():
        RES.joinpath(f"ic_launcher{suffix}_background.xml").write_text(BACKGROUND)
        RES.joinpath(f"ic_launcher{suffix}_foreground.xml").write_text(vector(shapes))
        RES.joinpath(f"ic_launcher{suffix}_monochrome.xml").write_text(vector(shapes, mono=True))
        name = "kanti" + suffix.replace("_", "-")
        BRAND.joinpath(f"{name}.svg").write_text(svg(shapes))
        BRAND.joinpath(f"{name}-monochrome.svg").write_text(svg(shapes, background=False, mono=True))
    # Notification: white silhouette, cropped so the mark fills the 24 dp status-bar icon (about 2 dp padding).
    crop = 62.0
    offset = -(108 - crop) / 2
    RES.joinpath("ic_stat.xml").write_text(vector(KANTI, mono=True, size=24, viewport=crop, scale=SCALE, translate=offset, white=True))
    BRAND.joinpath("kanti-notification.svg").write_text(
        svg(KANTI, background=False, mono=True, view=f"{fmt(-offset)} {fmt(-offset)} {fmt(crop)} {fmt(crop)}", size=24).replace("#000000", "#FFFFFF"))
    print("wrote", sorted(p.name for p in RES.glob("ic_*.xml")), sorted(p.name for p in BRAND.glob("*.svg")))
