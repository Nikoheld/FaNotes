/**
 * Attribute names and enumerated values from the desktop HTML completion
 * schema (`@codemirror/lang-html`). Local names come first, then the globals.
 * A null value list means the attribute is free text and offers no choices.
 */
internal fun htmlAttributeNames(tag: String): List<String> {
    val local = LOCAL_ATTRS[tag.lowercase()].orEmpty()
    return if (local.isEmpty()) GLOBAL_ATTR_NAMES else local + GLOBAL_ATTR_NAMES
}

/** Enumerated values for an attribute, or null when the desktop schema has none. */
internal fun htmlAttributeValues(tag: String, name: String): List<String>? {
    if (name in GLOBAL_ATTR_NAMES) return GLOBAL_VALUES[name]
    return TAG_VALUES["${tag.lowercase()}.$name"]
}

