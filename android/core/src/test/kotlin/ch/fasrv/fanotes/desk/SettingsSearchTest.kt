package ch.fasrv.fanotes.desk

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

class SettingsSearchTest {
    @Test
    fun settingsSearchMatchesEveryWordAndFoldsAccents() {
        assertEquals(emptyList(), searchSettings("   "))
        assertEquals("grosse", normalizeSettingsSearch("Größe"))
        assertEquals("grossen", normalizeSettingsSearch("Größen"))
        assertTrue(searchSettings("Größe").any { it.label == "Schriften & Textgrößen" })
        assertEquals("editor", searchSettings("zoom limit").single { it.label == "Zoom-Limit" }.section)
        assertEquals("editor", searchSettings("Rechtschreibung").single().section)
        assertEquals("settings-editor", searchSettings("Rechtschreibung").single().target)
        assertEquals("settings-zoom", searchSettings("zoom limit").single { it.label == "Zoom-Limit" }.target)
        assertEquals("settings-typography", searchSettings("Größe").single { it.label == "Schriften & Textgrößen" }.target)
        assertEquals("settings-note-backup", searchSettings("Backup").single().target)
        assertEquals("experimental", searchSettings("Backup").single().section)
        assertEquals("drawing", searchSettings("Handschrift").single { it.label == "Papier & Stift" }.section)
        assertTrue(searchSettings("GlyphenWerk").isEmpty())
        assertTrue(searchSettings("OneNote").isEmpty())
        assertTrue(searchSettings("vim modus").isEmpty())
        assertTrue(searchSettings("keinbegriff xyz").isEmpty())
        assertTrue(SETTINGS_SEARCH_ITEMS.none { it.label.contains("GlyphenWerk") })
        assertEquals(listOf("Aussehen & Schreiben", "Stift & Arbeitsbereich", "FaNotes & System"), settingsNavGroups().map { it.first })
        assertEquals("Darstellung", settingsNavGroups().first().second.first().label)
        assertEquals("Farben, Schriften und Dichte", SETTINGS_NAV.first { it.id == "appearance" }.detail)
        assertEquals("Stift & Erkennung", SETTINGS_NAV.first { it.id == "drawing" }.label)
        assertEquals("Dateien & Vault", SETTINGS_NAV.first { it.id == "files" }.label)
        assertEquals(43, SETTINGS_NAV_ROW_DP)
        assertEquals(9, SETTINGS_NAV_RADIUS_DP)
        assertEquals(650, SETTINGS_NAV_LABEL_WEIGHT)
        assertEquals(750, SETTINGS_NAV_GROUP_WEIGHT)
        assertEquals(0.08f, SETTINGS_NAV_GROUP_TRACKING)
        assertEquals(21, SETTINGS_TITLE_SP)
        assertEquals(-0.03f, SETTINGS_TITLE_TRACKING)
        assertEquals(47, SETTINGS_FOOTER_DP)
        assertEquals("Fertig", SETTINGS_DONE)
        assertEquals("Änderungen werden automatisch lokal gespeichert.", SETTINGS_SAVED)
        assertEquals(12, SETTINGS_NAV.first { it.id == "appearance" }.count)
        assertEquals(8, SETTINGS_NAV.first { it.id == "editor" }.count)
        assertEquals("Anpassung · 12 Optionen", settingsEyebrow(12))
        assertEquals("Einstellungen", SETTINGS_BRAND)
        assertEquals("FaNotes an dich anpassen", SETTINGS_BRAND_DETAIL)
        assertEquals("Einstellungen suchen", SETTINGS_SEARCH_PLACEHOLDER)
        assertEquals("Keine Treffer", settingsSearchCount(0))
        assertEquals("3 Treffer", settingsSearchCount(3))
        assertEquals(35, SETTINGS_SEARCH_DP)
        assertEquals(9, SETTINGS_SEARCH_RADIUS_DP)
        assertEquals(0.72f, SETTINGS_SEARCH_FILL_ALPHA)
        assertEquals(0.48f, SETTINGS_SEARCH_FOCUS_ALPHA)
        assertEquals(22, SETTINGS_SEARCH_CLEAR_DP)
        assertEquals(32, SETTINGS_BRAND_DP)
        assertEquals("files", searchSettings("Automatisch speichern").single().section)
        assertEquals("files", searchSettings("Tagesnotiz").single().section)
        assertEquals("appearance", searchSettings("Zeilenhöhe").single().section)
        assertEquals(0.12f, SETTINGS_EYEBROW_TRACKING)
        assertEquals(19, SETTINGS_SCROLL_PAD_TOP_DP)
        assertEquals(25, SETTINGS_SCROLL_PAD_X_DP)
        assertEquals(34, SETTINGS_SCROLL_PAD_BOTTOM_DP)
        assertEquals(12, SETTING_CARD_RADIUS_DP)
        assertEquals(14, SETTING_CARD_MARGIN_DP)
        assertEquals(0.70f, SETTING_CARD_FILL_ALPHA)
        assertEquals(39, SETTING_TITLE_DP)
        assertEquals(700, SETTING_TITLE_WEIGHT)
        assertEquals(0.06f, SETTING_TITLE_TRACKING)
        assertEquals(58, SETTING_ROW_MIN_DP)
        assertEquals(22, SETTING_ROW_GAP_DP)
        assertEquals(580, SETTING_COPY_WEIGHT)
        assertEquals(47, THEME_CHOICE_MIN_DP)
        assertEquals(23, SWATCH_DP)
        assertEquals(true, themeSwatch("system").split)
        assertEquals("#17181b", themeSwatch("midnight").background)
        assertEquals("#fbfaf7", themeSwatch("sepia").background)
    }
}
